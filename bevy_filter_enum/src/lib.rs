    #[derive(Component, Debug, Clone, PartialEq, Eq)]
    struct DownloadProgress {
        percent: u8,
    }

    #[allow(dead_code)]
    #[derive(Component, EnumFilter, Debug, Clone, PartialEq, Eq)]
    enum Download {
        Queued,
        #[enum_filter(extract)]
        Active(DownloadProgress),
        Finished,
    }

    #[test]
    fn extracted_payload_is_synced_immediately_on_insert() {
        let mut app = App::new();
        app.add_plugins(DownloadEnumFilterPlugin);

        let entity = app
            .world_mut()
            .spawn(Download::Active(DownloadProgress { percent: 40 }))
            .id();

        let entity_ref = app.world().entity(entity);
        assert!(entity_ref.contains::<DownloadActive>());
        assert_eq!(
            entity_ref.get::<DownloadProgress>(),
            Some(&DownloadProgress { percent: 40 })
        );
    }

    #[test]
    fn extracted_payload_update_replaces_without_readding() {
        let mut app = App::new();
        app.add_plugins(DownloadEnumFilterPlugin);
        observe_transitions::<DownloadProgress>(&mut app);

        let entity = app
            .world_mut()
            .spawn(Download::Active(DownloadProgress { percent: 40 }))
            .id();
        assert_eq!(
            transitions(&app),
            Transitions {
                add: 1,
                insert: 1,
                discard: 0,
                remove: 0,
            }
        );

        app.world_mut()
            .entity_mut(entity)
            .insert(Download::Active(DownloadProgress { percent: 80 }));
        assert_eq!(
            transitions(&app),
            Transitions {
                add: 1,
                insert: 2,
                discard: 1,
                remove: 0,
            },
            "a payload update within the same variant is a replace, not a remove and add",
        );
        assert_eq!(
            app.world().entity(entity).get::<DownloadProgress>(),
            Some(&DownloadProgress { percent: 80 })
        );
    }

    #[test]
    fn despawning_from_a_marker_observer_does_not_panic() {
        let mut app = App::new();
        app.add_plugins(DownloadEnumFilterPlugin);
        // The marker lands before the extracted payload does. An observer
        // reacting to the marker by despawning the entity must not make the
        // trailing payload insert blow up on the corpse.
        app.add_observer(|add: On<Add, DownloadActive>, mut commands: Commands| {
            commands.entity(add.entity).despawn();
        });

        let entity = app.world_mut().spawn(Download::Queued).id();
        app.world_mut()
            .entity_mut(entity)
            .insert(Download::Active(DownloadProgress { percent: 40 }));

        assert!(app.world().get_entity(entity).is_err());
    }

