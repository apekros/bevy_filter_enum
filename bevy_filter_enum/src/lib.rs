    #[derive(Component, Debug, Clone, PartialEq, Eq)]
    struct NavigatePayload {
        distance: u32,
    }

    #[allow(dead_code)]
    #[derive(Component, EnumFilter, Debug, Clone, PartialEq, Eq)]
    enum Progress {
        Idle,
        #[enum_filter(extract)]
        Navigate(NavigatePayload),
    }

    #[allow(dead_code)]
    #[derive(Component, EnumFilter, Debug, Clone, PartialEq, Eq)]
    enum Status {
        Created,
        #[enum_filter(extract)]
        Executing(Progress),
    }

    #[test]
    fn extraction_cascades_through_nested_enum_filters() {
        let mut app = App::new();
        app.add_plugins(StatusEnumFilterPlugin)
            .add_plugins(ProgressEnumFilterPlugin);

        let entity = app
            .world_mut()
            .spawn(Status::Executing(Progress::Navigate(NavigatePayload {
                distance: 12,
            })))
            .id();

        app.update();

        let entity_ref = app.world().entity(entity);
        assert!(entity_ref.contains::<StatusExecuting>());
        assert!(entity_ref.contains::<ProgressNavigate>());
        assert_eq!(
            entity_ref.get::<Progress>(),
            Some(&Progress::Navigate(NavigatePayload { distance: 12 }))
        );
        assert_eq!(
            entity_ref.get::<NavigatePayload>(),
            Some(&NavigatePayload { distance: 12 })
        );
    }

    #[test]
    fn extraction_cascade_unwinds_when_outer_variant_changes() {
        let mut app = App::new();
        app.add_plugins(StatusEnumFilterPlugin)
            .add_plugins(ProgressEnumFilterPlugin);

        let entity = app
            .world_mut()
            .spawn(Status::Executing(Progress::Navigate(NavigatePayload {
                distance: 12,
            })))
            .id();
        app.update();

        app.world_mut().entity_mut(entity).insert(Status::Created);
        app.update();

        let entity_ref = app.world().entity(entity);
        assert!(entity_ref.contains::<StatusCreated>());
        assert!(!entity_ref.contains::<Progress>());
        assert!(!entity_ref.contains::<ProgressNavigate>());
        assert!(!entity_ref.contains::<NavigatePayload>());
    }
