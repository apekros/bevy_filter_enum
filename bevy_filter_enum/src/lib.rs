use bevy_ecs::schedule::SystemSet;
use bevy_ecs::system::EntityCommands;

pub use bevy_filter_enum_derive::{EnumFilter, EnumFilterCollection};

/// Label for the `PreUpdate` systems every generated plugin uses to catch
/// in-place enum mutations. Order your own systems after this set when they
/// need to see markers that reflect changes made through `Mut<Enum>`.
///
/// Inserting or removing the enum through commands or `EntityWorldMut` is
/// handled by component hooks and is visible immediately, this set only
/// matters for `DerefMut` style edits.
#[derive(Debug, Hash, PartialEq, Eq, Clone, SystemSet)]
pub struct EnumFilterSystems;

/// Shared behavior generated by [`EnumFilter`] for enum values that can sync
/// marker components onto an entity.
///
/// Every method leaves markers that are already in the right state untouched,
/// so `Add` and `Remove` hooks and observers fire only on real variant
/// transitions and not when the enum is re-inserted with the same variant.
pub trait EnumFilterValue {
    /// Returns the generated marker index for this enum value.
    fn marker_index(&self) -> usize;

    /// Syncs the markers so that only the one at `index` is present.
    ///
    /// This is the fast path for a single active variant: one insert for the
    /// active marker and one bundle remove for the rest. Indexes outside the
    /// variant range are ignored.
    fn sync_marker_at(index: usize, entity: &mut EntityCommands<'_>);

    /// Syncs the markers so that only the one for this enum value is present.
    fn sync_marker(&self, entity: &mut EntityCommands<'_>) {
        Self::sync_marker_at(self.marker_index(), entity);
    }

    /// Brings the generated marker components in line with `active`: the
    /// marker for every index `active` accepts is added if missing, and every
    /// other marker is removed if present.
    ///
    /// Use this when several variants can be active at once, as with
    /// [`EnumFilterCollection`]. It queues one command per marker, so prefer
    /// [`sync_marker`](Self::sync_marker) when only one variant is active.
    fn sync_markers(active: impl Fn(usize) -> bool, entity: &mut EntityCommands<'_>);

    /// Removes all marker components generated for this enum type.
    fn remove_markers(entity: &mut EntityCommands<'_>);
}

